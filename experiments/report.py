"""Turn results/raw/*.json into results/results.md, results/tables/*.csv and results/figures/*.png."""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from bugpredictor import BENCHMARK, load_promise  # noqa: E402

RAW, OUT = ROOT / "results" / "raw", ROOT / "results"
FIG, TAB = OUT / "figures", OUT / "tables"
BLUE, BLUE_L, GREEN, RED, GREY, DARK = "#1a73e8", "#a5c0f7", "#2e9e44", "#d93025", "#9ca3af", "#1f2937"
MODELS = ["knn", "lr", "nb", "svm", "rf"]
GA_MODELS = ["knn", "svm", "lr"]
NAMES = {"knn": "k-NN", "lr": "Logistic regression", "nb": "Naive Bayes", "svm": "SVM (RBF)", "rf": "Random forest"}

plt.rcParams.update({"figure.dpi": 130, "savefig.dpi": 160, "font.size": 10, "axes.spines.top": False,
                     "axes.spines.right": False, "axes.grid": True, "grid.color": "#e5e7eb", "axes.axisbelow": True,
                     "axes.titleweight": "bold", "axes.titlesize": 11, "legend.frameon": False})


def load(name):
    return json.loads((RAW / f"{name}.json").read_text())


def f(x, d=3):
    return "–" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(header))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def write_csv(name, header, rows):
    TAB.mkdir(parents=True, exist_ok=True)
    with open(TAB / f"{name}.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


def save(fig, name):
    FIG.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(FIG / name, bbox_inches="tight")
    plt.close(fig)
    print("saved results/figures/" + name)


def original_claims():
    """Best F1 stored by the original notebooks (research/original/results), release unknown."""
    try:
        import pandas as pd
    except ImportError:
        return {}
    out = {}
    for x in sorted((ROOT / "research" / "original" / "results" / "knn").glob("*/*.xlsx")):
        try:
            best = pd.read_excel(x, sheet_name="Meilleure_Solution")
            out[x.parent.name] = float(best["Score_F1"].iloc[0])
        except Exception:
            pass
    return out


def make_report():
    base, leak, abl, tr = load("baseline"), load("leakage"), load("ablation"), load("transfer")
    ga = {m: {r: load(f"ga_{m}_{r}") for r in BENCHMARK} for m in GA_MODELS}
    gm = lambda m, r, side, k="f1": float(np.mean([x[side][k] for x in ga[m][r]["folds"]]))  # noqa: E731
    md = []

    # ------------------------------------------------------------------ datasets
    rows = []
    for r in BENCHMARK:
        s = base[r]["summary"]
        rows.append([r, s["modules"], s["defective"], f"{100 * s['defect_rate']:.1f} %", tr[r]["previous"]])
    md += ["# BugPredictor: results", "",
           "Generated by `python experiments/run_all.py` (raw numbers in `results/raw/`, tables in `results/tables/`).", "",
           "## Data", "",
           "One release per project from the PROMISE repository (20 CK/object-oriented metrics per Java class; "
           "a class is *defective* when at least one bug was linked to it). For each project, the latest release "
           "with 5 % to 70 % defective classes is used.", "",
           md_table(["Release", "Classes", "Defective", "Share", "Previous release (cross-version)"], rows), ""]

    # ------------------------------------------------------------------ 1. leakage
    claims = original_claims()
    rows, csv_rows = [], []
    for r in BENCHMARK:
        L = leak[r]
        row = [r, f(L["knn1_leaky"]["f1"]), f(L["knn1_honest"]["f1"]), f(L["knn5_leaky"]["f1"]), f(L["knn5_honest"]["f1"]),
               f(L["ga_leaky_reported"]), f(gm("knn", r, "ga")), f(gm("knn", r, "default"))]
        rows.append(row)
        csv_rows.append([r, L["knn1_leaky"]["f1"], L["knn1_honest"]["f1"], L["knn5_leaky"]["f1"], L["knn5_honest"]["f1"],
                         L["ga_leaky_reported"], gm("knn", r, "ga"), gm("knn", r, "default")])
    means = np.mean(np.array([c[1:] for c in csv_rows], float), axis=0)
    rows.append(["**mean**"] + [f"**{f(v)}**" for v in means])
    header = ["Release", "1-NN, SMOTE before CV", "1-NN, SMOTE in folds", "5-NN, before", "5-NN, in folds",
              "GA, original protocol", "GA, nested CV", "Default 5-NN"]
    write_csv("leakage", ["release"] + header[1:], csv_rows)
    md += ["## 1. The leakage of the original protocol", "",
           "The original notebooks standardised the data and applied SMOTE to the **whole dataset**, then ran "
           "cross-validation (and the GA) on the resampled rows. A synthetic class is an interpolation between a real "
           "class and one of its neighbours, so most test folds contain near-copies of training rows (and synthetic "
           "rows are themselves tested). The table re-runs both protocols on the same releases; F1 of the defective class.", "",
           md_table(header, rows), "",
           f"The original protocol reports a mean F1 of **{means[4]:.3f}** for the GA-optimised k-NN; evaluated without "
           f"leakage (nested cross-validation, SMOTE fitted inside each training fold) the same method reaches "
           f"**{means[5]:.3f}**. The 1-NN classifier, which the original GA kept choosing, shows the mechanism most "
           f"clearly: {means[0]:.3f} with SMOTE before the split, {means[1]:.3f} with SMOTE inside the folds.", ""]
    if claims:
        md += ["For reference, the result files stored by the original notebooks (`research/original/results/knn/`, "
               "release not recorded) report these best F1 scores: " +
               ", ".join(f"{k} {v:.3f}" for k, v in claims.items()) + ".", ""]
    md += ["![Leakage](figures/1_leakage.png)", ""]
    fig, ax = plt.subplots(figsize=(10, 3.8))
    x = np.arange(len(BENCHMARK))
    w = 0.27
    ax.bar(x - w, [c[5] for c in csv_rows], w, color=RED, label="original protocol (SMOTE before CV)")
    ax.bar(x, [c[6] for c in csv_rows], w, color=GREEN, label="GA, nested CV (leakage-free)")
    ax.bar(x + w, [c[7] for c in csv_rows], w, color=BLUE_L, label="default 5-NN (leakage-free)")
    ax.set_xticks(x, BENCHMARK, rotation=30, ha="right")
    ax.set_ylim(0, 1)
    ax.set_ylabel("F1 (defective class)")
    ax.set_title("k-NN + genetic algorithm: reported vs real performance")
    ax.legend(ncol=3, loc="upper center", bbox_to_anchor=(0.5, -0.32))
    save(fig, "1_leakage.png")

    # ------------------------------------------------------------------ 2. default models
    rows, csv_rows = [], []
    for r in BENCHMARK:
        rows.append([r] + [f"{f(base[r][m]['mean']['f1'])} ± {f(base[r][m]['std']['f1'], 2)}" for m in MODELS])
        csv_rows.append([r] + [base[r][m]["mean"][k] for m in MODELS for k in ("f1", "mcc", "auc", "recall_20")])
    summary = {k: {m: float(np.mean([base[r][m]["mean"][k] for r in BENCHMARK])) for m in MODELS}
               for k in ("f1", "mcc", "auc", "recall_20", "precision", "recall", "pf")}
    manual = float(np.mean([base[r]["manual_up"] for r in BENCHMARK]))
    write_csv("baseline", ["release"] + [f"{m}_{k}" for m in MODELS for k in ("f1", "mcc", "auc", "recall_20")], csv_rows)
    md += ["## 2. Default models", "",
           "Repeated stratified cross-validation (5 × 5 folds). In every fold, imputation, the log(1 + x) transform, "
           "standardisation and SMOTE are fitted on the training rows only. F1 ± standard deviation over the 25 folds:", "",
           md_table(["Release"] + [NAMES[m] for m in MODELS], rows), "",
           "Mean over the 11 releases:", "",
           md_table(["Metric"] + [NAMES[m] for m in MODELS],
                    [[{"f1": "F1", "mcc": "MCC", "auc": "AUC", "recall_20": "Recall@20%LOC", "precision": "Precision",
                       "recall": "Recall", "pf": "False-alarm rate"}[k]] + [f(summary[k][m]) for m in MODELS]
                     for k in summary]), "",
           f"*Recall@20%LOC*: share of the defective classes found when classes are inspected by decreasing predicted "
           f"risk per line of code, until 20 % of the code has been read. The simple *smallest classes first* baseline "
           f"(ManualUp) reaches **{manual:.3f}** on the same releases.", "",
           "![Default models](figures/2_default_models.png)", ""]
    fig, ax = plt.subplots(figsize=(7.2, 5))
    M = np.array([[base[r][m]["mean"]["f1"] for m in MODELS] for r in BENCHMARK] + [[summary["f1"][m] for m in MODELS]])
    im = ax.imshow(M, cmap="Blues", vmin=0.2, vmax=0.9, aspect="auto")
    ax.set_xticks(range(len(MODELS)), [NAMES[m] for m in MODELS], rotation=20, ha="right")
    ax.set_yticks(range(len(BENCHMARK) + 1), BENCHMARK + ["mean"])
    ax.grid(False)
    for i in range(M.shape[0]):
        for j in range(M.shape[1]):
            ax.text(j, i, f"{M[i, j]:.2f}", ha="center", va="center", fontsize=9,
                    color="white" if M[i, j] > 0.6 else DARK, fontweight="bold" if i == M.shape[0] - 1 else None)
    ax.axhline(len(BENCHMARK) - 0.5, color="white", lw=3)
    ax.set_title("F1 of the default models (5 × 5-fold CV)")
    fig.colorbar(im, ax=ax, fraction=0.04)
    save(fig, "2_default_models.png")

    # ------------------------------------------------------------------ 3. GA
    md += ["## 3. Genetic algorithm, nested cross-validation", "",
           "Outer loop: 5 stratified folds. On the training part of each outer fold, the GA (population 20, up to "
           "15 generations, tournament selection, uniform crossover, elitism) searches a subset of the 20 metrics and the "
           "hyperparameters, scoring each individual by the mean F1 of an **inner** 5-fold cross-validation (minus 0.005 "
           "per metric kept). The chosen model is then retrained on the whole training part and scored on the outer test "
           "fold, which the search never saw. The default model is scored on the same folds.", ""]
    summary_rows, csv_rows = [], []
    fig, axes = plt.subplots(1, 3, figsize=(11, 4.6), sharey=True)
    for ax, m in zip(axes, GA_MODELS):
        rows = []
        for i, r in enumerate(BENCHMARK):
            d0, g0 = gm(m, r, "default"), gm(m, r, "ga")
            nfeat = np.mean([len(x["features"]) for x in ga[m][r]["folds"]])
            inner = np.mean([x["inner_cv_f1"] for x in ga[m][r]["folds"]])
            rows.append([r, f(d0), f(g0), f"{g0 - d0:+.3f}", f(gm(m, r, "default", "mcc")), f(gm(m, r, "ga", "mcc")),
                         f(gm(m, r, "default", "auc")), f(gm(m, r, "ga", "auc")), f"{nfeat:.1f}", f(inner)])
            csv_rows.append([m, r, d0, g0, gm(m, r, "default", "mcc"), gm(m, r, "ga", "mcc"), gm(m, r, "default", "auc"),
                             gm(m, r, "ga", "auc"), nfeat, inner, ga[m][r]["seconds"]])
            col = GREEN if g0 >= d0 else RED
            ax.plot([d0, g0], [i, i], color=col, lw=2, zorder=1)
            ax.scatter([d0], [i], color=BLUE_L, edgecolor=BLUE, s=40, zorder=2)
            ax.scatter([g0], [i], color=col, s=40, zorder=3)
            ax.text(max(d0, g0) + 0.015, i, f"{nfeat:.0f}", va="center", fontsize=8, color=GREY)
        sub = [c for c in csv_rows if c[0] == m]
        dmean, gmean_ = np.mean([c[2] for c in sub]), np.mean([c[3] for c in sub])
        wins = sum(c[3] > c[2] for c in sub)
        rows.append(["**mean**", f"**{f(dmean)}**", f"**{f(gmean_)}**", f"**{gmean_ - dmean:+.3f}**",
                     f(np.mean([c[4] for c in sub])), f(np.mean([c[5] for c in sub])), f(np.mean([c[6] for c in sub])),
                     f(np.mean([c[7] for c in sub])), f"{np.mean([c[8] for c in sub]):.1f}", f(np.mean([c[9] for c in sub]))])
        summary_rows.append([NAMES[m], f(dmean), f(gmean_), f"{gmean_ - dmean:+.3f}", f"{wins} / {len(sub)}",
                             f"{np.mean([c[8] for c in sub]):.1f} / 20", f(np.mean([c[9] for c in sub]))])
        md += [f"### {NAMES[m]}", "",
               md_table(["Release", "F1 default", "F1 GA", "Δ F1", "MCC default", "MCC GA", "AUC default", "AUC GA",
                         "Metrics kept", "GA's inner-CV F1"], rows), ""]
        ax.set_yticks(range(len(BENCHMARK)), BENCHMARK)
        ax.set_title(NAMES[m])
        ax.set_xlabel("F1 on outer test folds")
        ax.set_xlim(0.15, 1.0)
    axes[0].invert_yaxis()
    from matplotlib.lines import Line2D
    handles = [Line2D([], [], marker="o", ls="", markerfacecolor=BLUE_L, markeredgecolor=BLUE, label="default model"),
               Line2D([], [], marker="o", ls="", color=GREEN, label="GA better"),
               Line2D([], [], marker="o", ls="", color=RED, label="GA worse")]
    fig.legend(handles=handles, loc="lower center", ncol=3, bbox_to_anchor=(0.5, -0.04))
    fig.suptitle("Default vs GA-optimised models (numbers: metrics kept out of 20)", fontweight="bold")
    save(fig, "3_ga_vs_default.png")
    write_csv("ga_nested_cv", ["model", "release", "f1_default", "f1_ga", "mcc_default", "mcc_ga", "auc_default", "auc_ga",
                               "features_kept", "inner_cv_f1", "seconds"], csv_rows)
    md += ["### Summary", "",
           md_table(["Model", "F1 default", "F1 GA", "Δ F1", "GA better on", "Metrics kept", "GA's own estimate (inner CV)"],
                    summary_rows), "",
           "The last column is the F1 the GA *believed* it had reached, measured on the folds it was optimising; the gap "
           "with the outer test score is the optimism that a non-nested protocol would have reported as a result.", "",
           "![GA vs default](figures/3_ga_vs_default.png)", "", "![Optimism](figures/4_ga_optimism.png)", "",
           "![Convergence](figures/6_ga_convergence.png)", ""]

    # optimism scatter
    fig, ax = plt.subplots(figsize=(5.2, 4.6))
    for m, c in zip(GA_MODELS, [BLUE, "#f59e0b", GREEN]):
        inner = [x["inner_cv_f1"] for r in BENCHMARK for x in ga[m][r]["folds"]]
        outer = [x["ga"]["f1"] for r in BENCHMARK for x in ga[m][r]["folds"]]
        ax.scatter(inner, outer, s=16, alpha=0.6, color=c, label=NAMES[m])
    ax.plot([0, 1], [0, 1], color=DARK, lw=1, ls="--")
    ax.set_xlim(0, 1); ax.set_ylim(0, 1)
    ax.set_xlabel("F1 estimated by the GA (inner CV)")
    ax.set_ylabel("F1 on the outer test fold")
    ax.set_title("The GA's own estimate is optimistic")
    ax.legend(loc="upper left")
    save(fig, "4_ga_optimism.png")

    # feature selection frequency
    feats = load_promise(BENCHMARK[0]).features
    runs = [x for m in GA_MODELS for r in BENCHMARK for x in ga[m][r]["folds"]]
    freq = {ft: sum(ft in x["features"] for x in runs) / len(runs) for ft in feats}
    order = sorted(feats, key=lambda ft: freq[ft])
    fig, ax = plt.subplots(figsize=(5.4, 5.2))
    ax.barh(order, [freq[ft] for ft in order], color=BLUE_L, edgecolor=BLUE, lw=0.6)
    ax.set_xlim(0, max(0.6, max(freq.values()) + 0.05))
    ax.set_xlabel(f"share of the {len(runs)} GA runs that kept the metric")
    ax.set_title("Metrics selected by the genetic algorithm")
    save(fig, "5_feature_selection.png")
    write_csv("feature_selection", ["metric", "share_of_runs"], [[ft, freq[ft]] for ft in sorted(feats, key=lambda q: -freq[q])])
    top = sorted(feats, key=lambda q: -freq[q])
    md += ["## 4. Which metrics does the GA keep?", "",
           f"Over {len(runs)} GA runs (3 models × 11 releases × 5 outer folds), the most often selected metrics are " +
           ", ".join(f"`{q}` ({100 * freq[q]:.0f} %)" for q in top[:6]) + "; the least often " +
           ", ".join(f"`{q}` ({100 * freq[q]:.0f} %)" for q in top[-4:]) + ".", "",
           "![Feature selection](figures/5_feature_selection.png)", ""]

    # convergence example
    ex = ga["knn"]["camel-1.6"]["folds"][0]
    h = ex["history"]
    fig, ax = plt.subplots(figsize=(5.6, 3.6))
    ax.plot([q["generation"] for q in h], [q["best"] for q in h], "o-", color=GREEN, ms=4,
            label="best fitness (inner-CV F1 − 0.005 per metric)")
    ax.plot([q["generation"] for q in h], [q["mean"] for q in h], color=BLUE_L, lw=2, label="population mean fitness")
    ax.axhline(ex["ga"]["f1"], color=RED, ls="--", lw=1.2, label="chosen model: F1 on the outer test fold")
    ax.axhline(ex["default"]["f1"], color=BLUE, ls=":", lw=1.2, label="default model: F1 on the outer test fold")
    ax.set_xlabel("generation")
    ax.set_ylabel("F1")
    ax.set_title("GA run on camel-1.6 (k-NN, outer fold 1)")
    ax.legend(fontsize=8, loc="upper center", bbox_to_anchor=(0.5, -0.2), ncol=2)
    save(fig, "6_ga_convergence.png")

    # ------------------------------------------------------------------ 5. ablation
    rows = []
    for m in ["knn", "lr", "nb", "svm"]:
        rows.append([NAMES[m]] + [f(np.mean([abl[r][m][v]["f1"] for r in BENCHMARK])) for v in ("full", "no_log", "no_smote")] +
                    [f(np.mean([abl[r][m][v]["recall"] for r in BENCHMARK])) for v in ("full", "no_smote")])
    md += ["## 5. Preprocessing choices", "",
           "Mean over the 11 releases, 3 × 5-fold CV. Each variant removes one step of the pipeline.", "",
           md_table(["Model", "F1 full pipeline", "F1 without log", "F1 without SMOTE", "Recall full", "Recall without SMOTE"], rows), ""]

    # ------------------------------------------------------------------ 6. transfer
    rows, csv_rows = [], []
    for m in MODELS:
        within = np.mean([base[r][m]["mean"]["f1"] for r in BENCHMARK])
        cv = np.mean([tr[r]["cross_version"][m]["f1"] for r in BENCHMARK])
        cp = np.mean([tr[r]["cross_project"][m]["f1"] for r in BENCHMARK])
        auc_cv = np.mean([tr[r]["cross_version"][m]["auc"] for r in BENCHMARK])
        auc_cp = np.mean([tr[r]["cross_project"][m]["auc"] for r in BENCHMARK])
        rows.append([NAMES[m], f(within), f(cv), f(cp), f(np.mean([base[r][m]["mean"]["auc"] for r in BENCHMARK])), f(auc_cv), f(auc_cp)])
        csv_rows.append([m, within, cv, cp])
    write_csv("transfer", ["model", "f1_within_cv", "f1_cross_version", "f1_cross_project"], csv_rows)
    md += ["## 6. Predicting a new release, or a new project", "",
           "*Cross-version*: train on the previous release of the same project, test on the release above (the realistic "
           "use: learn from the last release, predict the next one). *Cross-project*: train on the 10 other releases "
           "pooled, test on this one. Mean over the 11 releases:", "",
           md_table(["Model", "F1 within (CV)", "F1 cross-version", "F1 cross-project", "AUC within", "AUC cross-version",
                     "AUC cross-project"], rows), "", "![Transfer](figures/7_transfer.png)", ""]
    fig, ax = plt.subplots(figsize=(7, 3.4))
    x = np.arange(len(MODELS))
    for k, (lab, col) in enumerate([("within project (CV)", BLUE_L), ("previous release", BLUE), ("other projects", GREEN)]):
        ax.bar(x + (k - 1) * 0.27, [c[k + 1] for c in csv_rows], 0.27, color=col, label=lab)
    ax.set_xticks(x, [NAMES[m] for m in MODELS])
    ax.set_ylim(0, 0.8)
    ax.set_ylabel("mean F1")
    ax.set_title("Where the training data comes from")
    ax.legend(ncol=3, fontsize=8, loc="upper center", bbox_to_anchor=(0.5, -0.12))
    save(fig, "7_transfer.png")

    (OUT / "results.md").write_text("\n".join(md) + "\n")
    print("saved results/results.md")
    sys.path.insert(0, str(ROOT / "tools"))
    from build_web import build_research  # noqa: E402
    build_research()


if __name__ == "__main__":
    make_report()
